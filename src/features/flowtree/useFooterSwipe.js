import { useRef, useState } from 'react'

// Keep native button taps/keyboard activation; capture only a horizontal drag.
export default function useFooterSwipe() {
  const gesture = useRef(null)
  const suppressClick = useRef(false)
  const [preview, setPreview] = useState(null)
  const reset = () => { gesture.current = null; setPreview(null) }
  const indexAt = (nav, x, y) => [...nav.children].findIndex(button => {
    const r = button.getBoundingClientRect()
    return x >= r.left && x <= r.right && y >= r.top && y <= r.bottom
  })
  return {
    preview,
    handlers: {
      onPointerDown(event) {
        suppressClick.current = false
        if (!event.isPrimary || event.button !== 0) return
        gesture.current = { id: event.pointerId, x: event.clientX, y: event.clientY, dragging: false }
      },
      onPointerMove(event) {
        const g = gesture.current
        if (!g || g.id !== event.pointerId) return
        const dx = Math.abs(event.clientX - g.x)
        const dy = Math.abs(event.clientY - g.y)
        if (!g.dragging) {
          if (dy > 8 && dy > dx) { reset(); return }
          if (dx < 8 || dx <= dy) return
          g.dragging = true
          event.currentTarget.setPointerCapture(event.pointerId)
        }
        setPreview(indexAt(event.currentTarget, event.clientX, event.clientY))
      },
      onPointerUp(event) {
        const g = gesture.current
        if (!g || g.id !== event.pointerId) return
        const nav = event.currentTarget
        const index = indexAt(nav, event.clientX, event.clientY)
        reset()
        if (!g.dragging) return
        if (nav.hasPointerCapture(event.pointerId)) nav.releasePointerCapture(event.pointerId)
        if (index >= 0) nav.children[index].click()
        // Ignore the compatibility click generated by this pointer release.
        suppressClick.current = true
      },
      onPointerCancel: reset,
      onLostPointerCapture: reset,
      onClickCapture(event) {
        if (suppressClick.current && event.detail !== 0) {
          event.preventDefault()
          event.stopPropagation()
          suppressClick.current = false
        }
      },
    },
  }
}
